"""Generate buildless web messages and native Android resources from one reviewed catalogue."""
from pathlib import Path
import hashlib,json,re
from xml.sax.saxutils import escape
ROOT=Path(__file__).resolve().parent.parent
messages=json.loads((ROOT/'locales/messages.json').read_text(encoding='utf-8'))
for source,values in messages.items():
 assert len(values) in (2,3) and all(isinstance(v,str) and v for v in values), source
 for value in values: assert set(re.findall(r'\{\d+\}',source))==set(re.findall(r'\{\d+\}',value)),source
(ROOT/'web/js/messages.js').write_text('// Generated by scripts/generate-locales.py; edit locales/messages.json.\nexport const messages = '+json.dumps(messages,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
ids={source:'msg_'+hashlib.sha256(source.encode()).hexdigest()[:12] for source in messages}
assert len(set(ids.values()))==len(ids)
for locale,index in [('values',None),('values-en',0),('values-es',1)]:
 folder=ROOT/'android/app/src/main/res'/locale;folder.mkdir(exist_ok=True)
 def xml(s):return escape(s.replace('\\','\\\\').replace("'","\\'").replace('"','\\"').replace('\n','\\n'))
 (folder/'messages.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated; edit locales/messages.json. -->\n<resources>\n'+''.join(f'    <string name="{ids[k]}" formatted="false">{xml((v[2] if len(v)==3 else k) if index is None else v[index])}</string>\n' for k,v in messages.items())+'</resources>\n',encoding='utf-8')
def kotlin(s):return json.dumps(s,ensure_ascii=False).replace('$','\\$')
folder=ROOT/'android/app/src/main/java/it/tabatastudio/i18n';folder.mkdir(exist_ok=True)
(folder/'MessageIds.kt').write_text('// Generated by scripts/generate-locales.py.\npackage it.tabatastudio.i18n\nimport it.tabatastudio.R\ninternal val messageIds = mapOf(\n'+',\n'.join(f'    {kotlin(k)} to R.string.{v}' for k,v in ids.items())+'\n)\n',encoding='utf-8')
print(f'{len(messages)} complete Italian/English/Spanish messages generated; placeholders verified.')
